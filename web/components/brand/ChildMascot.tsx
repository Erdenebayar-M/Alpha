/** Reveal-mode eye leaf (gender step): whole combined eye art (white + pupil
 *  + glint) moves as one unit, driven by `.child-eye` in globals.css — no
 *  separate gaze split here, matching mobile's BOY_EYES_DRIVEN (which wraps
 *  the same combined Yellow art `withEyeOpen`, not the split white/pupil
 *  files GazeBoyEye* below uses). */
function RevealBoyEye({
  side,
  box,
  fromX,
  glintFilterId,
}: {
  side: "left" | "right";
  box: { left: number; top: number; width: number; height: number };
  fromX: number;
  glintFilterId: string;
}) {
  const eye = YELLOW_EYE[side];
  return (
    <svg x={box.left} y={box.top} width={box.width} height={box.height} viewBox={eye.viewBox}>
      {/* The animated class lives on this <g>, not the <svg> above: fill-box
          centring is reliable on a shape/group but not on a nested viewport
          <svg>, where it anchors near the element's own x/y/width/height box
          instead of what's actually drawn inside it — the squash read as
          closing toward the top instead of the eye's own centre. */}
      <g className="child-eye" style={{ "--from-x": `${fromX}px` } as CSSProperties}>
        <path d={eye.white} fill="white" />
        <path d={eye.pupil} fill="#050505" />
        {eye.glint ? <EyeGlint filterId={glintFilterId} /> : null}
      </g>
    </svg>
  );
}

